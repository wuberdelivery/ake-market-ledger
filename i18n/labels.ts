const DICTS: Record<Language, Dict> = { en, yo, ha, ig };

export function t(
  lang: Language,
  key: string,
  vars?: Record<string, string | number>
): string {
  let s = DICTS[lang][key] ?? DICTS.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.split(`{${k}}`).join(String(v)); // replaceAll needs ES2021; split/join works everywhere
    }
  }
  return s;
}
